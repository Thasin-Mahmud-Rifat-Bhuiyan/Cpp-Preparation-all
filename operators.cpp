#include<iostream>
using namespace std;
int main()
{
    int x=4;
    cout<<(x==7)<<endl; //false
    cout<<(x==4)<<endl; //true
    cout<<(x=4)<<endl; //4
    cout<<(x!=4)<<endl; //false
    cout<<(x!=7)<<endl; //true
    cout<<(x>7)<<endl; //false
    cout<<(x<7)<<endl; //true
    cout<<(x>=4)<<endl; //true
    
}